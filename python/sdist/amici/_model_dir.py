"""Ownership and completion markers for model directories.

Model import writes generated code and the compiled extension into a model
directory. A marker file in that directory records that AMICI created the
directory, which top-level entries it created, and how far the import got.
This allows to

* safely remove previous imports, but refuse to remove directories or files
  not created by AMICI,
* distinguish complete model directories from those left behind by a failed
  or interrupted import (see :func:`is_model_dir_complete`).
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import shutil
import sys
from collections.abc import Iterable
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path

#: Name of the marker file in a model directory
MARKER_FILENAME = ".amici_model.json"
#: Version of the marker file format. Increase on incompatible changes.
MARKER_FORMAT_VERSION = 1


class ModelDirStatus(StrEnum):
    """Import status of a model directory."""

    #: Import started, but code generation is not complete
    IMPORTING = "importing"
    #: Model code generated, but not compiled (complete for JAX models)
    GENERATED = "generated"
    #: Model extension compiled
    COMPILED = "compiled"


class ModelBackend(StrEnum):
    """Simulation backend of the model in a model directory."""

    SUNDIALS = "sundials"
    JAX = "jax"


# top-level directories created after code generation, which are not
#  recorded in the marker: by compiling a model extension, or by importing
#  a JAX model
_BUILD_DIRS = ("build", "build_model_ext", "*.egg-info")
_CACHE_DIRS = ("__pycache__",)
_UNRECORDED_DIRS = {
    ModelBackend.SUNDIALS: (*_BUILD_DIRS, *_CACHE_DIRS),
    ModelBackend.JAX: _CACHE_DIRS,
}

# Top-level entries in model directories created by AMICI versions before
#  the marker file was introduced, or by imports that failed before
#  recording their entries. `{model_name}` is the name of the model package.
_GENERATED_FILES = {
    ModelBackend.SUNDIALS: (
        "*.cpp",
        "*.h",
        ".gitignore",
        "CMakeLists.txt",
        "MANIFEST.in",
        "setup.py",
    ),
    ModelBackend.JAX: ("*.py",),
}
_GENERATED_DIRS = {
    ModelBackend.SUNDIALS: (
        "swig",
        "{model_name}",
        *_UNRECORDED_DIRS[ModelBackend.SUNDIALS],
    ),
    ModelBackend.JAX: _UNRECORDED_DIRS[ModelBackend.JAX],
}

# signatures identifying files generated by AMICI versions before the
#  marker file was introduced
_SETUP_PY_SIGNATURES = (
    '"""AMICI model package setup"""',
    "AMICI-generated module for model ",
)
_SETUP_PY_MODEL_NAME = re.compile(
    r"""description=(["'])AMICI-generated module for model (\w+)\1"""
)
_JAX_INIT_SIGNATURES = (
    re.compile(
        r"^from amici\.(sim\.)?jax\.model import JAXModel\b", re.MULTILINE
    ),
    re.compile(
        r"^class JAXModel_(\w+)\(JAXModel\):$.*^Model = JAXModel_\1$",
        re.MULTILINE | re.DOTALL,
    ),
)
# temporary files of marker updates
_MARKER_TMP_FILE = re.compile(rf"{re.escape(MARKER_FILENAME)}\.\d+\.tmp")


def prepare_model_dir(
    model_dir: str | Path, model_name: str, jax: bool = False
) -> None:
    """Create a model directory for a new import.

    If the directory exists, it must be empty or contain a previous model
    import, which is removed, including the contents of all subdirectories
    created by AMICI. If the directory contains any other top-level files or
    directories, nothing is removed. Afterwards, the directory only contains
    a new marker file.

    :param model_dir:
        The model directory.
    :param model_name:
        Name of the model to be imported.
    :param jax:
        Whether a JAX model is to be imported.
    :raises FileExistsError:
        If the directory contains files that were not created by AMICI.
    :raises PermissionError:
        If the previous import cannot be removed, e.g., on Windows, if the
        previously imported model is still loaded.
    """
    model_dir = Path(model_dir)
    model_dir.mkdir(parents=True, exist_ok=True)

    marker = _read_marker(model_dir)
    if marker is not None and marker["format_version"] > MARKER_FORMAT_VERSION:
        raise FileExistsError(
            f"Cannot import model into {model_dir}: The directory was "
            "created by a newer AMICI version. Remove it or choose a "
            "different output directory."
        )

    # only remove the entries that were checked
    entries = _list_entries(model_dir)
    if foreign := _get_foreign_entries(model_dir, entries):
        raise FileExistsError(
            f"Cannot import model into {model_dir}: The directory contains "
            f"files that were not created by AMICI: {', '.join(foreign)}. "
            "Remove them or choose a different output directory."
        )

    # the marker is kept, so the directory remains recognizable as created
    #  by AMICI if this is interrupted
    try:
        for entry in entries:
            if _is_dir(entry):
                shutil.rmtree(entry)
            else:
                entry.unlink()
    except PermissionError as e:
        hint = (
            " On Windows, this happens if the previously imported model is "
            "still loaded by a running Python process. Close it or choose a "
            "different output directory."
            if sys.platform == "win32"
            else ""
        )
        raise PermissionError(
            f"Cannot remove the previous model import from {model_dir}: "
            f"{e}.{hint}"
        ) from e
    for entry in model_dir.iterdir():
        if _MARKER_TMP_FILE.fullmatch(entry.name) and entry.is_file():
            entry.unlink(missing_ok=True)

    _write_marker(
        model_dir,
        {
            "model_name": model_name,
            "backend": ModelBackend.JAX if jax else ModelBackend.SUNDIALS,
            "status": ModelDirStatus.IMPORTING,
            "entries": [],
        },
    )


def get_foreign_entries(model_dir: str | Path) -> list[str]:
    """Get the top-level entries of a model directory not created by AMICI.

    :param model_dir:
        The model directory.
    :returns:
        Sorted names of the top-level entries not known to be created by
        AMICI. All entries, if the directory is not recognized as created by
        AMICI.
    """
    model_dir = Path(model_dir)
    try:
        entries = _list_entries(model_dir)
    except FileNotFoundError:
        return []
    return _get_foreign_entries(model_dir, entries)


def _list_entries(model_dir: Path) -> list[Path]:
    """List the top-level entries of a model directory except the marker."""
    return [
        entry
        for entry in model_dir.iterdir()
        if entry.name != MARKER_FILENAME
        # leftovers of an interrupted marker update
        and not (_MARKER_TMP_FILE.fullmatch(entry.name) and entry.is_file())
    ]


def _get_foreign_entries(model_dir: Path, entries: list[Path]) -> list[str]:
    """Get the names of the given entries not created by AMICI."""
    marker = _read_marker(model_dir)
    if marker is not None and marker["format_version"] > MARKER_FORMAT_VERSION:
        # unknown format
        return sorted(entry.name for entry in entries)

    if marker is not None and marker["status"] != ModelDirStatus.IMPORTING:
        # the previous import recorded what it created
        recorded = set(marker.get("entries", []))
        unrecorded_dirs = _UNRECORDED_DIRS[marker["backend"]]
        return sorted(
            entry.name
            for entry in entries
            if entry.name not in recorded
            and not (_is_dir(entry) and _matches(entry.name, unrecorded_dirs))
        )

    if marker is not None:
        # the previous import was interrupted during code generation
        backend = marker["backend"]
        model_name = marker.get("model_name")
    else:
        backend, model_name = _identify_legacy_model_dir(model_dir)

    if backend not in _GENERATED_FILES:
        return sorted(entry.name for entry in entries)

    dir_patterns = [
        pattern.format(model_name=model_name)
        for pattern in _GENERATED_DIRS[backend]
        if model_name or "{model_name}" not in pattern
    ]
    return sorted(
        entry.name
        for entry in entries
        if not (_is_dir(entry) and _matches(entry.name, dir_patterns))
        and not (
            entry.is_file()
            and not entry.is_symlink()
            and _matches(entry.name, _GENERATED_FILES[backend])
        )
    )


def _is_dir(path: Path) -> bool:
    """Check whether a path is a directory, but not a symlink or junction."""
    return path.is_dir() and not path.is_symlink() and not path.is_junction()


def _matches(name: str, patterns: Iterable[str]) -> bool:
    """Check whether a file name matches any of the glob patterns.

    Matching is case-sensitive on all platforms.
    """
    return any(fnmatch.fnmatchcase(name, pattern) for pattern in patterns)


def _identify_legacy_model_dir(
    model_dir: Path,
) -> tuple[ModelBackend | None, str | None]:
    """Identify a model directory created by an AMICI version without
    marker files.

    :returns: ``(backend, model_name)``. ``backend`` is ``None`` if the
        directory was not recognized as created by AMICI. ``model_name``
        is ``None`` if unknown.
    """
    try:
        setup_py = (model_dir / "setup.py").read_text()
    except (OSError, UnicodeDecodeError):
        setup_py = ""
    if all(signature in setup_py for signature in _SETUP_PY_SIGNATURES):
        match = _SETUP_PY_MODEL_NAME.search(setup_py)
        return ModelBackend.SUNDIALS, match.group(2) if match else None

    try:
        init_py = (model_dir / "__init__.py").read_text()
    except (OSError, UnicodeDecodeError):
        init_py = ""
    if all(signature.search(init_py) for signature in _JAX_INIT_SIGNATURES):
        return ModelBackend.JAX, None

    return None, None


def set_model_dir_status(
    model_dir: str | Path, status: ModelDirStatus
) -> None:
    """Update the import status in the marker of a model directory.

    When code generation completes, i.e., on the first status update after
    :func:`prepare_model_dir`, the current top-level entries of the model
    directory are recorded as created by AMICI. Does nothing if the directory
    has no marker.

    :param model_dir:
        The model directory.
    :param status:
        The new status.
    """
    model_dir = Path(model_dir)
    marker = _read_marker(model_dir)
    if marker is None or marker["format_version"] > MARKER_FORMAT_VERSION:
        return
    if marker["status"] == ModelDirStatus.IMPORTING:
        marker["entries"] = sorted(
            entry.name for entry in _list_entries(model_dir)
        )
    marker["status"] = ModelDirStatus(status)
    _write_marker(model_dir, marker)


def get_model_dir_status(model_dir: str | Path) -> ModelDirStatus | None:
    """Get the import status from the marker of a model directory.

    :returns: The status, or ``None`` if there is no valid marker, or the
        marker has an unknown format.
    """
    marker = _read_marker(Path(model_dir))
    return None if marker is None else marker["status"]


def is_model_dir_complete(
    model_dir: str | Path, jax: bool = False, compiled: bool = True
) -> bool:
    """Check whether a model directory contains a usable model.

    :param model_dir:
        The model directory.
    :param jax:
        Whether a JAX model is expected.
    :param compiled:
        Whether a compiled model extension is required. Only relevant for
        non-JAX models.
    :returns:
        ``True`` if the last import into this directory completed with the
        currently installed AMICI version and the requested backend,
        ``False`` otherwise, e.g., if the import failed, or was done with a
        different AMICI version.
    """
    from . import __version__

    marker = _read_marker(Path(model_dir))
    if marker is None or marker.get("amici_version") != __version__:
        return False
    status = marker["status"]
    if jax:
        return (
            marker["backend"] == ModelBackend.JAX
            and status == ModelDirStatus.GENERATED
        )
    if marker["backend"] != ModelBackend.SUNDIALS:
        return False
    if compiled:
        return status == ModelDirStatus.COMPILED
    return status in (ModelDirStatus.GENERATED, ModelDirStatus.COMPILED)


def _read_marker(model_dir: Path) -> dict | None:
    """Read the marker file.

    :returns: The marker, or ``None`` if there is no valid marker. The
        marker may have a newer, unknown ``format_version``. In that case,
        its ``status`` and ``backend`` are ``None``.
    """
    try:
        marker = json.loads((model_dir / MARKER_FILENAME).read_text())
    except (OSError, ValueError):
        return None
    if (
        not isinstance(marker, dict)
        or type(marker.get("format_version")) is not int
    ):
        return None
    if marker["format_version"] > MARKER_FORMAT_VERSION:
        marker["status"] = marker["backend"] = None
        return marker
    try:
        marker["status"] = ModelDirStatus(marker.get("status"))
        marker["backend"] = ModelBackend(marker.get("backend"))
    except ValueError:
        return None
    return marker


def _write_marker(model_dir: Path, marker: dict) -> None:
    """Write the marker file atomically."""
    from . import __version__

    marker = marker | {
        "format_version": MARKER_FORMAT_VERSION,
        "amici_version": __version__,
        "modified": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    tmp_file = model_dir / f"{MARKER_FILENAME}.{os.getpid()}.tmp"
    tmp_file.write_text(json.dumps(marker, indent=2))
    os.replace(tmp_file, model_dir / MARKER_FILENAME)
